/**
 * Reproducible end-to-end evaluation of the self-improvement loop, in an isolated
 * data directory (your working database is untouched). Writes docs/EVALUATION.md.
 *
 *   npm run eval:report            (add ANTHROPIC_API_KEY to use Claude for proposals/policy compilation)
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "contextloop-eval-"));
process.env.CONTEXTLOOP_DATA_DIR = tmp;

const { ROOT, get } = await import("../db.js");
const { seed } = await import("../seed.js");
const { resolvePrincipal } = await import("../auth.js");
const { proposeImprovement, getProposal, refineProposal, decideProposal, runLiveExecutions } = await import("../engine/skills.js");
const { runEvaluation } = await import("../eval/harness.js");
const { skillStats } = await import("../engine/traces.js");
const { llmEnabled, MODEL } = await import("../llm.js");

const log = (s: string) => console.log(`\x1b[36m▸\x1b[0m ${s}`);
const pct = (v: number | null) => (v == null ? "n/a" : `${(v * 100).toFixed(0)}%`);
const LIVE_N = Number(process.env.LIVE_N ?? 60);

log(`Seeding isolated demo org in ${tmp}`);
await seed({ quiet: true });
const alice = resolvePrincipal({ userId: "u_alice" })!;
const skill = get("SELECT * FROM skills WHERE slug = 'api-integration'")!;

log(`Baseline: ${LIVE_N} live executions on v1`);
const before = await runLiveExecutions("api-integration", LIVE_N, "u_alice");

log("Detect + propose");
const pid = (await proposeImprovement(skill.id, "u_alice"))!;
let prop = getProposal(pid)!;

log("Evaluate proposal (round 1)");
const ev1 = await runEvaluation({ skillId: skill.id, proposalId: pid, baseline: { label: "v1", content: prop.base_content }, candidate: { label: "proposal r1", content: prop.proposed_content } });

log("Refine from evaluation failures");
const refine = await refineProposal(pid, ev1, alice);
prop = getProposal(pid)!;

log("Evaluate proposal (round 2)");
const ev2 = await runEvaluation({ skillId: skill.id, proposalId: pid, baseline: { label: "v1", content: prop.base_content }, candidate: { label: "proposal r2", content: prop.proposed_content } });

log("Approve → v2 active + synced");
decideProposal(pid, "approve", "u_alice", "eval-report");

log(`After: ${LIVE_N} live executions on v2`);
const after = await runLiveExecutions("api-integration", LIVE_N, "u_alice");
const stats = skillStats(skill.id);

const caseTable = (ev: any) =>
  ["| Case | Origin | v1 | Candidate |", "|---|---|---|---|", ...ev.results.map((r: any) => `| ${r.case.label} | ${r.case.origin.replace("_", " ")} | ${r.baseline.status === "success" ? "✅" : "❌"} ${r.baseline.outcome} | ${r.candidate.status === "success" ? "✅" : "❌"} ${r.candidate.outcome} (${r.candidate.attempts} attempt${r.candidate.attempts > 1 ? "s" : ""}) |`)].join("\n");
const policyTable = (ev: any) => {
  const keys = Object.keys(ev.baseline_policy);
  return ["| Policy field | v1 | Candidate |", "|---|---|---|", ...keys.map((k) => `| \`${k}\` | ${ev.baseline_policy[k]} | ${ev.candidate_policy[k]} |`)].join("\n");
};

const md = `# Evaluation results: self-improving \`api-integration\` skill

_Generated by \`npm run eval:report\` on ${new Date().toISOString().slice(0, 10)}. Engine: ${llmEnabled() ? `Claude (${MODEL})` : "deterministic offline engine (no API key)"}. Every number below comes from real HTTP executions against the fault-injecting PayFlow sandbox._

## Headline

| | v1 (original) | v2 (approved) |
|---|---|---|
| Replay of historical failures + regression/control cases | ${pct(ev2.baseline_rate)} | **${pct(ev2.candidate_rate)}** |
| Live production-mix executions (n=${LIVE_N} each) | ${before.succeeded}/${before.executed} (${pct(before.succeeded / before.executed)}) | **${after.succeeded}/${after.executed} (${pct(after.succeeded / after.executed)})** |

## How the loop ran

1. **Detect**: recurring failure clusters mined from ${prop.stats.runs} historical runs: ${prop.evidence.clusters.map((c: any) => `\`${c.errorType}\` ×${c.count}`).join(", ")}.
2. **Propose** (${prop.generator}): ${prop.analysis}
3. **Evaluate, round 1**: candidate scored **${pct(ev1.candidate_rate)}** vs v1 ${pct(ev1.baseline_rate)} on ${ev1.results.length} cases, but the harness caught ${ev1.results.filter((r: any) => r.candidate.status === "failure").length} failing case(s): ${[...new Set(ev1.results.filter((r: any) => r.candidate.status === "failure").map((r: any) => `${r.case.label} → *${r.candidate.outcome}*`))].join("; ")}. Adding retries without idempotency turned a slow-but-committed charge into a **double charge**. v1 never retried, so that failure mode didn't appear in any historical trace.
4. **Refine**: ${refine.changed ? `revised for \`${(refine as any).errorTypes.join(", ")}\`, grounded in: ${(refine as any).knowledge.map((k: any) => `“${k.title}”`).join(", ")}` : (refine as any).reason}.
5. **Evaluate, round 2**: **${pct(ev2.candidate_rate)}** on ${ev2.results.length} cases.
6. **Approve → sync**: v2 activated and written to the Claude Code and Codex skill directories.
7. **Measure**: success by version on real (non-eval) executions: ${stats.byVersion.map((v: any) => `v${v.v} ${pct(v.rate)} (${v.ok}/${v.runs})`).join(" · ")}.

## Compiled execution policy (round 2)

The policy compiler turns each SKILL.md into the concrete behaviour an agent follows (${ev2.compiler === "claude" ? "Claude" : "rule-based parser"}).

${policyTable(ev2)}

## Round 1 cases

${caseTable(ev1)}

## Round 2 cases

${caseTable(ev2)}

## Final skill (v2)

\`\`\`markdown
${prop.proposed_content.trim()}
\`\`\`

## Method notes

- **Cases** are built from the skill's most recent failed traces that carry fault metadata (scenario + recovery point), plus two regression cases (healthy, slow-but-healthy) and one control (invalid card must fail fast, without retries).
- **Executor**: real \`fetch\` calls with \`AbortSignal\` timeouts against a local HTTP server; a 2.5 s task deadline models the agent's tool budget. Duplicate charges are detected server-side from per-run state.
- **Live executions** sample the production traffic mix (50% healthy, 18% latency spikes, 10% 503s, 8% 429s, 6% timeout-after-commit, 5% slow, 3% invalid card) and are recorded as ordinary traces.
- Randomness (traffic sampling, jitter) means live numbers vary slightly between runs; the replay evaluation is deterministic for a given case set.
`;

const out = path.join(ROOT, "docs", "EVALUATION.md");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, md);
log(`Wrote ${out}`);
console.log(`\n  replay: v1 ${pct(ev2.baseline_rate)} → v2 ${pct(ev2.candidate_rate)}   live: v1 ${before.succeeded}/${before.executed} → v2 ${after.succeeded}/${after.executed}\n`);
process.exit(0);
